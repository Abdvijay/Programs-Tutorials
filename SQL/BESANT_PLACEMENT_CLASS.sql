/* QN - Find the max salary of the employees department-wise */

SELECT 
	D.DEPT_NAME,
    MAX(E.EMP_SALARY) AS MAX_SALARY
FROM EMPLOYEE E
JOIN DEPARTMENT D
ON D.DEPT_ID = E.DEPT_ID
GROUP BY D.DEPT_NAME;

