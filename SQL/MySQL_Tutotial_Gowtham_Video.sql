# ------------------------- WINDOW FUNCTION ----------------------------------------

CREATE TABLE SALES(
	TRANSACTION_ID INT,
    STORE VARCHAR(20),
    SALES_AMOUNT DECIMAL(10,2)
);

INSERT INTO SALES
