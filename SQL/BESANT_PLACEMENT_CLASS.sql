/* QN - Combine three tables and return emp name, dept name, college, course (degree) */
SELECT 
    E.EMP_NAME AS EMPLOYEE_NAME,
    D.DEPT_NAME AS DEPARTMENT_NAME,
    ED.COLLEGE AS COLLEGE_NAME,
    ED.DEGREE  AS DEGREE_NAME
FROM EMPLOYEE E
JOIN DEPARTMENT D 
    ON E.DEPT_ID = D.DEPT_ID
JOIN EDUCATION ED 
    ON E.EMP_ID = ED.EMP_ID;
    
