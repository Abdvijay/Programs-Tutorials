SELECT * FROM REGEX_SAMPLES;

SELECT * FROM REGEX_SAMPLES WHERE SAMPLE_TEXT REGEXP '^A';                  # MATCHES STARTING WITH A CHARACTER
SELECT * FROM REGEX_SAMPLES WHERE SAMPLE_TEXT REGEXP 'ING$';                # MATCHES ENDING WITH ING CHARACTER
SELECT * FROM REGEX_SAMPLES WHERE SAMPLE_TEXT REGEXP '^[0-9]';              # MATCHES ONLY NUMERIC VALUES 0 TO 9
SELECT * FROM REGEX_SAMPLES WHERE SAMPLE_TEXT REGEXP '(.)\\1';              # MATCHES ONLY TWO CONTINUES LETTER WORDS JUST LIKE APPLE,FERRY BECAUSE IN THIS P AND R CONTINUES SO.
SELECT * FROM REGEX_SAMPLES WHERE SAMPLE_TEXT REGEXP '^[A-Za-z]+$';         # MATCHES A SENTENCE WHICH CONTAINS ONLY LETTERS
SELECT * FROM REGEX_SAMPLES WHERE SAMPLE_TEXT REGEXP '^.{5}$';              # MATCHES ANY FIVE CHARACTER WORDS
SELECT * FROM REGEX_SAMPLES WHERE SAMPLE_TEXT REGEXP '^(APPLE|BANANA)$';    # MATCHES ONLY APPLE AND BANANA
SELECT * FROM REGEX_SAMPLES WHERE SAMPLE_TEXT REGEXP '^[0-9]{3}[A-Z]+$';    # MATCHES ONLY STARTING WITH 3 NUMERIC AND AFTER THAT LETTERS WORDS

