2	BOB	    IT	    2021-07-10
3	CHARLIE	FINANCE	2020-09-30

# 2. RANK(), DENSE_RANK()

CREATE TABLE STUDENT_WINDOW(
	 STUDENT_ID INT,
     STUDENT_NAME VARCHAR(20),
     SCORE INT
);

INSERT INTO STUDENT_WINDOW
VALUES
(1, 'ALICE', 95),
(2, 'BOB', 90),
(3, 'CHARLIE', 95),
(4, 'DAVID', 85),
(5, 'EVA', 90);

POINTS TO REMEMBER :

    1. RANK() -> IF TWO ROWS ARE SAME THE PUT 1 FOR EACH AND NEXT ROW PUT 3 BECAUSE IT WORKS AS COUNT WISE.

SELECT
	STUDENT_ID, STUDENT_NAME, SCORE,
    RANK() OVER(ORDER BY SCORE DESC) AS RANK_OF_STUDENT
FROM STUDENT_WINDOW;

1	ALICE	95	1
3	CHARLIE	95	1
2	BOB	    90	3
5	EVA	    90	3
4	DAVID	85	5

POINTS TO REMEMBER :

    1. DENSE_RANK() -> IT WORKS AS IF BOTH ARE IN RANK 1 THEN PUT 1 FOR BOTH AND NEXT ROW NUMBER IS 2 AS WELL AS.
    2. THIS IS THE ONLY DIFF BETWEEN RANK() AND DENSE_RANK().

SELECT
	STUDENT_ID, STUDENT_NAME, SCORE,
    DENSE_RANK() OVER(ORDER BY SCORE DESC) AS RANK_OF_STUDENT
FROM STUDENT_WINDOW;

1	ALICE	95	1
3	CHARLIE	95	1
2	BOB	    90	2
5	EVA	    90	2
4	DAVID	85	3