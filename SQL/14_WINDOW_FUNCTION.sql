	WHEN LEAD(SALEAMOUNT) OVER(ORDER BY SALEDATE) - SALEAMOUNT IS NULL THEN SALEAMOUNT
    ELSE LEAD(SALEAMOUNT) OVER(ORDER BY SALEDATE) - SALEAMOUNT
    END AS SALESDIFF
