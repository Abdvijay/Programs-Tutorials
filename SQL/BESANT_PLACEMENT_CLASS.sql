/* QN - Find the employees for whom department is not assigned */

SELECT
	E.EMP_ID AS EMPLOYEE_ID,
    E.EMP_NAME AS EMPLOYEE_NAME
FROM EMPLOYEE E
LEFT JOIN DEPARTMENT D
ON E.DEPT_ID = D.DEPT_ID
WHERE D.DEPT_ID IS NULL;

