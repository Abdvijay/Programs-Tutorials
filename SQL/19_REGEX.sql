# --------------------------------- CHEAT SHEET ---------------------------------

^      - START OF STRING ANCHOR          - ASSERTS THAT THE FOLLOWING PATTERN MUST OCCUR AT THE BEGINNING OF THE STRING.    - ^Hello MATCHES "HELLO WORLD"
$      - END   OF STRING ANCHOR          - ASSERTS THAT THE PRECEDING PATTERN MUST OCCUR AT THE END OF THE STRING.          - WORRD$ MATCHES "HELLO WORLD"
.      - ANY CHARACTER                   - MATCHES ANY SINGLE CHARACTER EXCEPT A NEWLINE.                                   - A.C MATCHES "ABC","A-B","A.C"
*      - ZERO OR MORE                    - MATCHES ZERO OR MORE OCCURENCES OF THE PRECEDING ELEMENT.                        - AB*C MATCHES "AC","ABC","ABBC",ETC 
+      - ONE OR MORE                     - MATCHES ONE OR MORE OCCURENCES OF THE PRECEDING ELEMENT.                         - AB+C MATCHES "ABC","ABBC" BUT NOT "AC"  
?      - ZERO OR ONE                     - MATCHES ZERO OR ONE OCCURENCES OF THE PRECEDING ELEMENT.                         - COLOU?R MATCHES BOTH "COLOR" AND "COLOUR"
{N}    - EXACT COUNT                     - MATHCES EXACTLY N OCCURENCES OF THE PRECEDING ELEMENT.                           - A{3} MATCHES "AAA"
{N,}   - ATLEAST N OR MORE OCCURENCES    - MATCHES N OR MORE OCCURENCES OF THE PRECEDING ELEMENT.                           - A{2,} MATCHES "AA","AAAA","AAAA",ETC
{N,M}  - RANGE OF OCCURENCES             - MATCHES BETWEEN N AND M OCCURENCES OF THE PRECEDING ELEMENT.                     - A{2,4} MATCHES "AA","AAA","AAAA"
[ABC]  - CHARACTER CLASS                 - MATCHES ANY ONE OF THE CHARACTERS ENCLOSED IN THE BRACKETS.                      - [ABC] MATCHES "A","B" OR "C"
[^ABC] - NEGATED CHARACTER CLASS         - MATCHES ANY CHARACTER NOT LISTED BETWEEN THE BRACKETS.                           - [^ABC] MATCHES ANY CHARACTER EXCEPT "A","B","C"
(ABC)  - GROUPING AND CAPTURING          - GROUPS THE CHARACTERS "ABC" TOGETHER, WHICH CAN THEN BE REFERENCED LATER.        - (ABC)+ MATCHES "ABC","ABCABC",ETC
|      - ALTERNATION(OR)                 - MATCHES THE EXPRESSION BEFORE OR AFTER THE | SYMBOL.                             - CAT|DOG MATCHES "CAT" OR "DOG"           
\d     - DIGIT CHARACTER                 - MATCHES ANY SINGLE DIGIT(EQUIVALENT TO [0-9])                                    - \d MATCHES "0","1",....
\D     - NON DIGIT CHARACTER             - MATCHES ANY CHARACTER THAT IS NOT A DIGIT.                                       - \D MATCHES LETTER OR SYMBOL
\W     - NON WORD CHARACTER              - MATCHES ANY CHARACTER THAT IS NOT A WORD CHARACTER.                              - \W MATCHES PUNCTUATION AND SPACES,ETC
\w     - WORD CHARACTER                  - MATCHES ANY ALPHANUMERIC CHARACTER OR UNDERSCORE(EQUIVALENT TO [A-Za-z0-9]_)     - \w MATCHES LETTERS,DIGITS AND UNDERSCORE.
\s     - WHITESPACE CHARACTER            - MATCHES SPACES,TABS,NEWLINES AND OTHER WHITESPACE.                               - \s MATCHES SINGLE SPACES OR TAB.
\S     - NON-WHITESPACE CHARACTER        - MATCHES ANY CHARACTER THAT IS NOT WHITESPACE.                                    - \S MATCHES LETTERS,DIGITS AND PUNCTUATION AND ETC.
\b     - WORD BOUNDARY                   - ASSERTS A POSITION BETWEEN A WORD CHARACTER AND A NON WORD CHARACTER.            - \bWORD\b MATCHES "WORD" AS A WHOLE WORD (NOT PART OF "SWORD" OR "WORDS")
\B     - NON WORD BOUNDARY               - ASSERTS A POSITION THAT IS NOT A WORD BOUNDARY.                                  - \Bend MIGHT MATCH "bend" WITHIN A LONGER WORD LIKE "amendment"

CREATE TABLE REGEX_SAMPLES(
	ID INT AUTO_INCREMENT PRIMARY KEY,
    SAMPLE_TEXT VARCHAR(100)
);

