# -------------------------------------- STORED PROCEDURES -----------------------------------

# NOTE : A STORED PROCEDURE IS A PRECOMPILED SQL CODE BLOCK STORED IN THE DATABASE THAT CAN BE EXECUTED WHENEVER NEEDED.
# 		 IT IS ONE OF THE DATABASE OBJECTS.
#	     YOU SHOULD SELECT THE QUERY AND PROCEDURE AND CLICK THE THUNDER ICON TO EXECUTE IT WHILE USING PROCEDURE CONCEPT.
#		 IN,IN AND OUT,OUT,WITHOUT PARAMETER.

