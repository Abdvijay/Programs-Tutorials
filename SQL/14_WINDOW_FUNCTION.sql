# STORE WISE TRANSACTION

POINTS TO REMEMBER :

    1. IN GROUP BY WE ONLY GIVE ONE FIELD WHICH IS COMES UNDER GROUP BY.
    2. THE RESULTANT ROWS ARE SHRINK.
    3. WINDOW FUNCTIONS OVERCOME THESE DISADVANTAGES.

SELECT STORE,SUM(SALES_AMOUNT) AS AMOUNT FROM SALES
GROUP BY STORE;

A	450.00
B	550.00

POINTS TO REMEMBER :

    1. WE CAN GIVE MORE FIELDS IN DISPLAYING SECTION.
    2. OVER() -> DID AGGREATE ALL THE VALUES AND INSERTED INTO EVERY ROW.

SELECT 
	TRANSACTION_ID,STORE,SALES_AMOUNT,
    SUM(SALES_AMOUNT) OVER()
FROM SALES;

1	A	100.00	1000.00
2	A	200.00	1000.00
3	A	150.00	1000.00
4	B	250.00	1000.00
5	B	300.00	1000.00

POINTS TO REMEMBER :

    1. PARTITION BY -> USED TO PERFORM OPERATION BASED ON PARTITION BY.
    2. IN THIS SECTION CALCULATE THE SUM AMOUNT BASED ON STORE WHICH MEANS A HAS TOTAL AND B HAS SOME TOTAL LIKE WISE.
    3. ONE DIFF IS IN GROUP BY WE CANT USE MORE FIELDS DISPLAY BUT HERE WE CAN USE IT BY WINDOW FUNCTION.

SELECT 
	TRANSACTION_ID,STORE,SALES_AMOUNT,
    SUM(SALES_AMOUNT) OVER(PARTITION BY STORE) AS TOTAL
FROM SALES;

1	A	100.00	450.00
2	A	200.00	450.00
3	A	150.00	450.00
4	B	250.00	550.00
5	B	300.00	550.00

POINTS TO REMEMBER :

    1. HERE PARTITION BY STORE -> CALCULATE THE TOTAL AMOUNT BUT ORDER BY TRANSACTION_ID GIVES LIKE FIRST FIND TOTAL AND PUT IT AND NEXT FIND TOTAL AND ADD IT AND PUT IT LIKE WISE.
    2. BUT STORE WISE.

    ( EXAMPLE : MILK MAN POUR 1/2 LTR MILK WHICH IS 25 FOR FIRST DAY AND NEXT DAY CAME AND POUR 1 LTR WHICH COST IS 50 SO MILK MAN TOLD PENDING AMOUTN IS 75 ALONG TODAY ITSELF.
                NEXT DAY CAME AND POUR 1 LTR WHICH COST IS 50 SO TOTAL IS 125 FROM DAY 1 TO TILL.
                LIKE WISE ORDER BY PERFORMS IN WINDOW FUNCTION
    )
SELECT 
	TRANSACTION_ID,STORE,SALES_AMOUNT,
    SUM(SALES_AMOUNT) OVER(PARTITION BY STORE ORDER BY TRANSACTION_ID) AS TOTAL
FROM SALES;

