# --------------------- WINDOW FUNCTIONS -----------------------------------------------

NOTE :
    
    1. A WINDOW FUNCTIONS IN SQL PERFORMS A CALCULATION ACROSS A SET OF ROWS RELATED TO THE CURRENT ROW.
    2. WITHOUT CHANGING THE NUMBER OF ROWS IN THE  RESULT SET.
    3. THE TERM WINDOW REFERS TO A SET OF ROWS THAT ARE SOME HOW RELATED TO THE CURRENT ROW.

THREE TYPES :

    1. AGGREATE : ( AVG(), MAX(), MIN(), SUM(), COUNT() )
    2. RANKING  : ( ROW_NUMBER(), RANK(), DENSE_RANK(), PERCENT_RANK(), NTILE() )
    3. VALUE    : ( LAG(), LEAD(), FIRST_VALUE(), LAST_VALUE(), NTH_VALUE() )

