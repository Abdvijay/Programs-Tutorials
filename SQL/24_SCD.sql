CREATE TABLE CATEGORY_TYPE_3_SCD(
	PRODUCT_ID INT PRIMARY KEY,
    PRODCUT_TITLE VARCHAR(100),
    CURRENT_CATEGORY VARCHAR(100),
    PREVIOUS_CATEGORY VARCHAR(100)
);

INSERT INTO CATEGORY_TYPE_3_SCD VALUES
(201, 'AMAZON FIRE TV STICK', 'STREAMING DEVICES', NULL);

SELECT * FROM CATEGORY_TYPE_3_SCD;

PRODUCT_ID      PRODCUT_TITLE           CURRENT_CATEGORY        PREVIOUS_CATEGORY
201	            AMAZON FIRE TV STICK	STREAMING DEVICES	

UPDATE CATEGORY_TYPE_3_SCD
SET
	PREVIOUS_CATEGORY = CURRENT_CATEGORY,
    CURRENT_CATEGORY = 'MEDIA PLAYERS'
WHERE PRODUCT_ID = 201;

